/**
 * Regenerates every web brand derivative from the vector master.
 *
 *   node scripts/generate-brand-assets.mjs
 *
 * Source: assets/Logos Immonation/33 - Immonation Facelift Logo.svg — a CorelDRAW
 * export holding five paths: three for the mark ("Einzelnes I") and two for the
 * wordmark. Everything below is a crop/recolour of those paths, so the geometry
 * can never drift from the master.
 *
 * Outputs:
 *   public/brand/immonation-mark.svg          the CI element on its own
 *   public/brand/immonation-logo.svg          full logo, dark text
 *   public/brand/immonation-logo-inverse.svg  full logo, light text (dark grounds)
 *   src/app/icon.svg                          browser-tab icon
 *   src/app/favicon.ico                       48/32/16 px ICO for legacy clients
 *   src/app/apple-icon.png                    180 px iOS home-screen icon
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const MASTER = join(root, 'assets', 'Logos Immonation', '33 - Immonation Facelift Logo.svg')

/**
 * Registered brand values, taken literally from the master. These are trademark
 * colours, not design tokens — do not route them through the Tailwind theme.
 */
const BRAND = { fil0: '#1D9CD7', fil1: '#737372', fil2: '#A2D9F5' }
const TEXT_DARK = '#2B2A29'
/** Sampled from public/immonation-logo-white-text.png so the swap is pixel-neutral. */
const TEXT_LIGHT = '#D4D6D6'
/** Icon ground — the site's own --surface-dark. */
const ICON_GROUND = '#202322'

/** Ink bounds measured with getBBox() in Chromium against the unclipped master. */
const MARK_BOX = { x: 3306.57, y: 13477.13, w: 2440.71, h: 2746.8 }
const LOGO_BOX = { x: 3306.57, y: 13477.13, w: 14372.6, h: 2746.8 }

function readMasterPaths() {
  const src = readFileSync(MASTER, 'utf8')
  const paths = [...src.matchAll(/<path class="(fil[0-3])" d="([^"]+)"\/>/g)].map(([, cls, d]) => ({
    cls,
    d,
  }))
  if (paths.length !== 5) {
    throw new Error(`Master changed shape: expected 5 paths, found ${paths.length}`)
  }
  return {
    mark: paths.filter((p) => p.cls !== 'fil3'),
    text: paths.filter((p) => p.cls === 'fil3'),
  }
}

const renderPaths = (paths, fill) =>
  paths.map((p) => `    <path fill="${fill ?? BRAND[p.cls]}" d="${p.d}"/>`).join('\n')

const HEADER = (what) =>
  `<!-- Immonation ${what}.\n       Generated by scripts/generate-brand-assets.mjs from the vector master — do not hand-edit.\n       #1D9CD7 / #A2D9F5 / #737372 are registered brand values; do not recolour. -->`

/** Wraps paths in a viewBox cropped to the ink bounds. */
function croppedSvg({ box, body, title, what }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${box.w} ${box.h}" role="img" aria-label="${title}">
  ${HEADER(what)}
  <title>${title}</title>
  <g transform="translate(${-box.x} ${-box.y})">
${body}
  </g>
</svg>
`
}

/** Square icon: the mark centred on a solid ground, scaled to `fill` of the height. */
export function squareIcon({ mark, size = 512, ground = ICON_GROUND, fill = 0.74, comment }) {
  const height = size * fill
  const scale = height / MARK_BOX.h
  const width = MARK_BOX.w * scale
  const tx = (size - width) / 2 - MARK_BOX.x * scale
  const ty = (size - height) / 2 - MARK_BOX.y * scale
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">
  ${comment ?? HEADER('icon')}
  <rect width="${size}" height="${size}" fill="${ground}"/>
  <g transform="translate(${tx.toFixed(3)} ${ty.toFixed(3)}) scale(${scale.toFixed(6)})">
${renderPaths(mark)}
  </g>
</svg>
`
}

/** Wraps PNG frames in an ICO container (PNG-in-ICO, universally read since Vista). */
function buildIco(frames) {
  const header = Buffer.alloc(6)
  header.writeUInt16LE(0, 0) // reserved
  header.writeUInt16LE(1, 2) // type: icon
  header.writeUInt16LE(frames.length, 4)

  let offset = 6 + frames.length * 16
  const entries = frames.map(({ size, png }) => {
    const entry = Buffer.alloc(16)
    entry.writeUInt8(size >= 256 ? 0 : size, 0) // width (0 means 256)
    entry.writeUInt8(size >= 256 ? 0 : size, 1) // height
    entry.writeUInt8(0, 2) // palette colours
    entry.writeUInt8(0, 3) // reserved
    entry.writeUInt16LE(1, 4) // colour planes
    entry.writeUInt16LE(32, 6) // bits per pixel
    entry.writeUInt32LE(png.length, 8)
    entry.writeUInt32LE(offset, 12)
    offset += png.length
    return entry
  })

  return Buffer.concat([header, ...entries, ...frames.map((f) => f.png)])
}

async function rasterize(svg, size) {
  // next/og bundles satori + resvg; it rasterizes an inlined SVG data URI faithfully.
  const { ImageResponse } = await import('next/og.js')
  const response = new ImageResponse(
    {
      type: 'div',
      props: {
        style: { display: 'flex', width: '100%', height: '100%' },
        children: {
          type: 'img',
          props: {
            width: size,
            height: size,
            src: `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`,
          },
        },
      },
    },
    { width: size, height: size },
  )
  return Buffer.from(await response.arrayBuffer())
}

async function main() {
  const { mark, text } = readMasterPaths()

  mkdirSync(join(root, 'public', 'brand'), { recursive: true })

  const write = (path, contents) => {
    writeFileSync(join(root, path), contents)
    const bytes = typeof contents === 'string' ? Buffer.byteLength(contents) : contents.length
    console.log(`  ${path} (${(bytes / 1024).toFixed(1)} kB)`)
  }

  console.log('Brand derivatives:')

  write(
    'public/brand/immonation-mark.svg',
    croppedSvg({
      box: MARK_BOX,
      body: renderPaths(mark),
      title: 'Immonation',
      what: 'mark ("Einzelnes I")',
    }),
  )

  write(
    'public/brand/immonation-logo.svg',
    croppedSvg({
      box: LOGO_BOX,
      body: `${renderPaths(mark)}\n${renderPaths(text, TEXT_DARK)}`,
      title: 'Immonation GmbH',
      what: 'logo, dark text',
    }),
  )

  write(
    'public/brand/immonation-logo-inverse.svg',
    croppedSvg({
      box: LOGO_BOX,
      body: `${renderPaths(mark)}\n${renderPaths(text, TEXT_LIGHT)}`,
      title: 'Immonation GmbH',
      what: 'logo, light text for dark grounds',
    }),
  )

  // 0.74 of the frame: verified legible at 16 px, where a smaller mark turns to mush.
  write('src/app/icon.svg', squareIcon({ mark, size: 512, fill: 0.74 }))

  const icoSvg = squareIcon({ mark, size: 64, fill: 0.74 })
  const frames = []
  for (const size of [48, 32, 16]) {
    frames.push({ size, png: await rasterize(icoSvg, size) })
  }
  write('src/app/favicon.ico', buildIco(frames))

  // iOS rounds the corners of a home-screen icon, so the mark sits further back
  // from the edges here than it does in the tab icon. It must be raster: iOS
  // Safari ignores an SVG apple-touch-icon.
  write('src/app/apple-icon.png', await rasterize(squareIcon({ mark, size: 180, fill: 0.6 }), 180))
}

await main()
